import {chromium} from '@playwright/test';
import {mkdir,writeFile} from 'node:fs/promises';
const directory=new URL('../../ear-demo/',import.meta.url).pathname;
await mkdir(directory,{recursive:true});
const browser=await chromium.launch({channel:'chrome',headless:true});
const context=await browser.newContext({viewport:{width:1440,height:1000},recordVideo:{dir:directory,size:{width:1440,height:1000}}});
const page=await context.newPage(),errors=[],checkpoints=[];const start=Date.now();
page.on('pageerror',e=>errors.push(e.message));
async function shot(name,locator){if(locator)await locator.scrollIntoViewIfNeeded();await page.waitForTimeout(800);await page.screenshot({path:directory+name+'.png'});checkpoints.push({name,seconds:(Date.now()-start)/1000});await page.waitForTimeout(1800);}
await page.goto('http://127.0.0.1:5190');
await page.getByRole('button',{name:'Open original listening study',exact:true}).click();
const panel=page.getByRole('region',{name:'Work it out by ear'});
await panel.getByRole('button',{name:'Hear passage',exact:true}).waitFor();
await panel.getByRole('button',{name:'Hear passage',exact:true}).click();
await shot('01-listen',panel);
await panel.getByRole('button',{name:'Try without help',exact:true}).click();
await panel.getByLabel('Your chord 1',{exact:true}).fill('G');
await page.waitForTimeout(600);await panel.getByLabel('Your chord 2',{exact:true}).fill('Cmaj7');
await panel.getByRole('button',{name:'Check my proposal'}).click();
await panel.getByText('Root matches · quality differs',{exact:false}).waitFor();
await shot('02-quality-feedback',panel.locator('.ear-proposal'));
await panel.getByLabel('Your chord 1',{exact:true}).fill('G7');
await panel.getByRole('button',{name:'Hear my G7 proposal'}).click();
await page.waitForTimeout(1500);
await panel.getByRole('button',{name:'Prepare draft notes',exact:true}).click();
await panel.getByRole('button',{name:'Reveal draft · counts as help'}).waitFor({timeout:180000});
await panel.getByRole('button',{name:'Reveal draft · counts as help'}).click();
await shot('03-real-draft',panel.getByRole('heading',{name:'Model hypothesis',exact:true}));
const correction=panel.getByLabel(/^Correct /).first();const original=await correction.inputValue();
await correction.fill(original.startsWith('C')?'D4':'C4');await correction.press('Tab');
await panel.getByText('Your correction · confidence unknown',{exact:true}).first().waitFor();
await panel.getByRole('button',{name:'Show proposed tablature positions'}).click();
await shot('04-correction',panel.getByRole('heading',{name:'Model hypothesis',exact:true}));
await panel.getByRole('button',{name:'Play my proposal across the neck'}).click();
const studio=page.getByRole('region',{name:'Progression studio',exact:true});await studio.waitFor();
await studio.getByRole('button',{name:'Frets 5–9',exact:true}).click();
await shot('05-derived-workspace',studio.getByRole('group',{name:'Progression neck region',exact:true}));
await page.setViewportSize({width:390,height:844});
await shot('06-mobile',studio.getByRole('group',{name:'Progression neck region',exact:true}));
await writeFile(directory+'capture.json',JSON.stringify({errors,checkpoints,correction:{original,chosen:original.startsWith('C')?'D4':'C4',authority:'learner-confirmed'},purpose:'Actual local app; original CC0 synthesis; existing cached model-stage results'},null,2));
const video=page.video();await context.close();await video.saveAs(directory+'ear-workflow.webm');await browser.close();
console.log(JSON.stringify({directory,errors,checkpoints}));
