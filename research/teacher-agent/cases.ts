export const episodes: TeacherEpisode[] = lessons.flatMap((lesson) =>
  Array.from({ length: 8 }, (_, i) => {
    const c = context(lesson, i);
    return {
      id: `episode-${c.id}`,
      contextId: c.id,
      context: c,
      opening: prompts[lesson][i % 4]!,
      trajectory: i % 2 ? 'error-and-recovery' : 'question-and-transfer',
      maxTurns: 6,
      followups:
        i % 2
          ? [
              'I am not sure. Can you explain the difference using the notes I can see?',
              'I used the hint. Please do not count that as knowing it without help.',
              'Let me try a different example with the same idea.',
              'Why is that the right role in this chord?',
              'I want to stop here and review it later.',
            ]
          : [
              'Can you show or audition an example of that in this progression?',
              'What stayed the same, and what changed?',
              'I want to try a new position without the answer highlighted.',
              'Does that mean I played it correctly, or only answered the screen question?',
              'Give me one thing to practice next and explain why.',
            ],
      completion:
        'The episode addresses its goal, responds to the actual follow-ups, and ends with a supported next action or an appropriate stop. Scripted responses do not establish learning.',
    } satisfies TeacherEpisode;
  }),
);

/** Follow-ups depend on the observed surface. The harness never claims it played audio. */
export function scriptedFollowup(
  episode: TeacherEpisode,
  turn: number,
  surface: { offeredQuestion: boolean; offeredVariation: boolean },
): string {
  if (turn >= episode.maxTurns - 1) return episode.followups[4]!;
  if (surface.offeredQuestion && episode.trajectory === 'error-and-recovery')
    return 'I do not know the answer yet. Please explain it; this attempt should count as assisted.';
  if (surface.offeredVariation && turn === 0)
    return 'What changed in those notes, and what should I listen for?';
  return episode.followups[Math.min(turn, episode.followups.length - 1)]!;
}
