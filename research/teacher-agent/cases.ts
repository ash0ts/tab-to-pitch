/** Authored, synthetic teaching situations. No rows describe real learners. */
export type Lesson = 'foundations' | 'connections' | 'extensions';
export type EvidenceState = 'unseen' | 'incorrect' | 'assisted' | 'unassisted';
export interface TeachingContext {
  id: string;
  lesson: Lesson;
  key: string;
  chords: string[];
  tuning: number[];
  capo: number;
  minFret: number;
  maxFret: number;
  bassConfirmed: boolean;
  facts: { id: string; text: string }[];
}
export interface TeacherCase {
  id: string;
  contextId: string;
  suite: 'development' | 'fixed-history' | 'boundary';
  context: TeachingContext;
  evidence: EvidenceState;
  request: string;
  history: { role: 'user' | 'assistant'; text: string }[];
  goal: string;
  rubric: string[];
  forbiddenClaims: string[];
  boundary?: string;
}
export interface TeacherEpisode {
  id: string;
  contextId: string;
  context: TeachingContext;
  opening: string;
  trajectory: 'question-and-transfer' | 'error-and-recovery';
  maxTurns: 6;
  followups: string[];
  completion: string;
}
