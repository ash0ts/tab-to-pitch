function context(lesson: Lesson, i: number, development = false): TeachingContext {
  const k = keys[i % keys.length]!;
  const id = `${development ? 'dev' : 'test'}-${lesson}-${i + 1}`;
  return {
    id,
    lesson,
    key: k.key,
    chords: [k.ii, k.v, k.i, k.vi],
    tuning: [...tunings[i % tunings.length]!],
    capo: i % 3 === 2 ? 2 : 0,
    minFret: development ? 2 : [0, 5, 9, 2][i % 4]!,
    maxFret: development ? 10 : [7, 12, 16, 9][i % 4]!,
    bassConfirmed: i % 4 !== 3,
    facts: [
      { id: `${id}:seventh`, text: `${k.seventh} is the minor seventh of ${k.v}.` },
      { id: `${id}:third`, text: `${k.third} is the major third of ${k.i}.` },
      {
        id: `${id}:resolution`,
        text: `${k.seventh} can descend one semitone to ${k.third} when connecting ${k.v} to ${k.i}. This does not require every valid voicing to use that motion.`,
      },
      {
        id: `${id}:ninth`,
        text: `Adding ${k.ninth} to ${k.ii} adds its ninth. A four-voice ninth voicing can explicitly omit the fifth.`,
      },
      {
        id: `${id}:rootless`,
        text: `${k.rootless} are the third, fifth, and seventh of ${k.i}. That rootless interpretation requires the intended harmony and bass context; it is not the only interpretation in isolation.`,
      },
      {
        id: `${id}:key`,
        text: `The selected major key is ${k.key}; the authored progression is ii7–V7–Imaj7–vi7.`,
      },
    ],
  };
}
