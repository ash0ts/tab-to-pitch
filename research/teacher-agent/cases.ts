function makeCase(
  c: TeachingContext,
  evidence: EvidenceState,
  suite: TeacherCase['suite'],
): TeacherCase {
  const i = states.indexOf(evidence);
  return {
    id: `${c.id}-${evidence}`,
    contextId: c.id,
    suite,
    context: c,
    evidence,
    request: prompts[c.lesson][i]!,
    history:
      evidence === 'unseen'
        ? []
        : [
            {
              role: 'assistant',
              text: 'We are working with the selected progression and its chord tones.',
            },
            {
              role: 'user',
              text:
                evidence === 'incorrect'
                  ? 'My first answer was incorrect.'
                  : evidence === 'assisted'
                    ? 'I revealed the answer before responding.'
                    : 'I answered two different variants correctly without help.',
            },
          ],
    goal: goals[c.lesson],
    rubric: [
      'Answer the actual question using the selected musical context.',
      'Use observed answers and assistance accurately; do not invent a cause for a mistake.',
      'Choose a useful, feasible demonstration, question, clarification, or next action. There is no required action sequence.',
      'Keep explanations musically supported and manageable; preserve the learner’s stated goal.',
      evidence === 'assisted'
        ? 'Do not describe the revealed answer as unassisted recall.'
        : 'Distinguish screen knowledge evidence from playing and listening performance.',
    ],
    forbiddenClaims: [
      'The agent heard the learner play.',
      'The learner has permanently mastered the concept.',
      'Moving a neck position alone changes the mode.',
    ],
  };
}
export const fixedCases: TeacherCase[] = lessons.flatMap((lesson) =>
  Array.from({ length: 8 }, (_, i) => context(lesson, i)).flatMap((c) =>
    states.map((state) => makeCase(c, state, 'fixed-history')),
  ),
);
